class FlightData:
    def __init__(self, price, dep_city, dep_airport, dep_date, a_city, a_airport, r_date):
        self.price = price
        self.departure_city = dep_city,
        self.departure_airport = dep_airport,
        self.departure_date = dep_date,
        self.arrival_city = a_city,
        self.arrival_airport = a_airport,
        self.return_date = r_date

